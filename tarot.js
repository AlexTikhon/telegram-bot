function buildMinorArcana() {
  const cards = [];
  for (const suit of suits) {
    for (const rank of rankPatterns) {
      cards.push({
        name: `${rank.name} ${suit.name}`,
        upright: `${rank.pos} в сфере ${suit.themePos}.`,
        reversed: `${rank.neg} в сфере ${suit.themeNeg}.`
      });
    }
  }
  return cards;
}

const tarotDeck = [...majorArcana, ...buildMinorArcana()];

function seededRandom(seed) {
  let x = Math.sin(seed) * 10000;
  return x - Math.floor(x);
}

function hash(str) {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = (h << 5) - h + str.charCodeAt(i);
    h |= 0;
  }
  return Math.abs(h) || 1;
}

function getShuffledIndices(seed) {
  const indices = tarotDeck.map((_, i) => i);
  for (let i = indices.length - 1; i > 0; i--) {
    const r = seededRandom(seed + i);
    const j = Math.floor(r * (i + 1));
    [indices[i], indices[j]] = [indices[j], indices[i]];
  }
  return indices;
}

export function getDailyTarotSpread(chatId) {
  const today = new Date().toISOString().split("T")[0];
  const seed = hash(String(chatId) + ":" + today);

  const indices = getShuffledIndices(seed);
  const chosen = indices.slice(0, 3);

  const cards = chosen.map((idx, i) => {
    const card = tarotDeck[idx];
    const orientationRandom = seededRandom(seed + 100 + i);
    const isReversed = orientationRandom > 0.5;
    return {
      position: i + 1,
      name: card.name,
      orientation: isReversed ? "перевёрнутая" : "прямая",
      meaning: isReversed ? card.reversed : card.upright
    };
  });

  const lines = [];
  lines.push(`🃏 *Таро-расклад на сегодня* (${today})`);
  lines.push("");
  lines.push("_Это развлекательная трактовка, не воспринимай её как жёсткий прогноз судьбы._");
  lines.push("");

  for (const c of cards) {
    lines.push(
      `*${c.position}. ${c.name} (${c.orientation})*\n` +
      `${c.meaning}`
    );
    lines.push("");
  }

  return lines.join("\n");
}
